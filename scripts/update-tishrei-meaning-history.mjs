const pool = await getPool();
const isPostgres = process.env.DB_TYPE === 'postgres' || process.env.DB_TYPE === 'pg';
const placeholder = (index) => (isPostgres ? `$${index}` : '?');

const client = isPostgres ? await pool.connect() : await pool.getConnection();
try {
  await client.query('BEGIN');
  const updateResult = await client.query(
    `UPDATE articles
     SET short_description = ${placeholder(1)}, content = ${placeholder(2)}, is_free_html = ${placeholder(3)}
     WHERE id = ${placeholder(4)}`,
    [shortDescription, content, isPostgres ? false : 0, articleId]
  );
  const updatedRows = isPostgres ? updateResult.rowCount : updateResult[0].affectedRows;
  if (updatedRows !== 1) {
    throw new Error(`Expected to update article ${articleId}, updated ${updatedRows} rows.`);
  }

  const existingImages = await client.query(
    `SELECT id FROM article_images WHERE article_id = ${placeholder(1)} AND image_url = ${placeholder(2)}`,
    [articleId, '/uploads/holidays/tishrei-practical-guide.png']
  );
  const rows = isPostgres ? existingImages.rows : existingImages[0];
  if (rows.length === 0) {
    await client.query(
      `INSERT INTO article_images (article_id, image_url, alt_text, display_order)
       VALUES (${placeholder(1)}, ${placeholder(2)}, ${placeholder(3)}, ${placeholder(4)})`,
      [articleId, '/uploads/holidays/tishrei-practical-guide.png', 'שופר, ארבעת המינים ומחזור תפילה בחגי תשרי', 1]
    );
  }

  await client.query('COMMIT');
  const verification = await client.query(
    `SELECT LENGTH(content) AS content_length, is_free_html FROM articles WHERE id = ${placeholder(1)}`,
    [articleId]
  );
  const verifiedArticle = (isPostgres ? verification.rows : verification[0])[0];
  if (!verifiedArticle || Number(verifiedArticle.content_length) !== content.length || Boolean(verifiedArticle.is_free_html)) {
    throw new Error(`Article ${articleId} did not pass post-update verification.`);
  }
  console.log(`Verified article ${articleId}: ${content.length} characters of editor-compatible HTML and 2 inline images.`);
} catch (error) {
  await client.query('ROLLBACK');
  throw error;
} finally {
  client.release();
  await pool.end();
}
