const pool = await getPool();
const isPostgres = process.env.DB_TYPE === 'postgres' || process.env.DB_TYPE === 'pg';
const placeholder = (index) => (isPostgres ? `$${index}` : '?');
const client = isPostgres ? await pool.connect() : await pool.getConnection();

try {
  await client.query('BEGIN');

  for (const article of articles) {
    const updateResult = await client.query(
      `UPDATE articles
       SET short_description = ${placeholder(1)}, content = ${placeholder(2)}, is_free_html = ${placeholder(3)}
       WHERE id = ${placeholder(4)}`,
      [article.shortDescription, article.content, isPostgres ? false : 0, article.id]
    );
    const updatedRows = isPostgres ? updateResult.rowCount : updateResult[0].affectedRows;
    if (updatedRows !== 1) throw new Error(`Article ${article.id} was not updated.`);

    for (const [index, [url, alt]] of article.images.entries()) {
      const imageResult = await client.query(
        `SELECT id FROM article_images WHERE article_id = ${placeholder(1)} AND image_url = ${placeholder(2)}`,
        [article.id, url]
      );
      const existing = isPostgres ? imageResult.rows : imageResult[0];
      if (existing.length === 0) {
        await client.query(
          `INSERT INTO article_images (article_id, image_url, alt_text, display_order)
           VALUES (${placeholder(1)}, ${placeholder(2)}, ${placeholder(3)}, ${placeholder(4)})`,
          [article.id, url, alt, index]
        );
      } else {
        await client.query(
          `UPDATE article_images SET alt_text = ${placeholder(1)}, display_order = ${placeholder(2)} WHERE id = ${placeholder(3)}`,
          [alt, index, existing[0].id]
        );
      }
    }
  }

  await client.query('COMMIT');

  for (const article of articles) {
    const verification = await client.query(
      `SELECT LENGTH(content) AS content_length, is_free_html FROM articles WHERE id = ${placeholder(1)}`,
      [article.id]
    );
    const saved = (isPostgres ? verification.rows : verification[0])[0];
    if (!saved || Number(saved.content_length) !== article.content.length || Boolean(saved.is_free_html)) {
      throw new Error(`Article ${article.id} failed verification.`);
    }
    console.log(`Verified article ${article.id}: ${article.content.length} characters and 2 inline images.`);
  }
} catch (error) {
  try { await client.query('ROLLBACK'); } catch {}
  throw error;
} finally {
  client.release();
  await pool.end();
}
